const LANGS = ['en', 'ru'];
let LANG = (() => {
  let saved = null;
  try { saved = localStorage.getItem('bc-lang'); } catch {}
  if (LANGS.includes(saved)) return saved;
  return (navigator.language || '').toLowerCase().startsWith('ru') ? 'ru' : 'en';
})();

// t('key', {n: 3, name: 'Ana'}) — {placeholders} are filled from params; plural tables pick a form from params.n.
function t(key, params = {}) {
  let s = I18N[LANG][key] ?? I18N.en[key] ?? key;
  if (typeof s === 'object') s = s[new Intl.PluralRules(LANG).select(params.n)] ?? s.other;
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? params[k] : m));
}
